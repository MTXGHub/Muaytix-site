/* Assembles the paste-ready block for Muay Thai Bangkok Tonight.
 *
 *   node extract-copy.mjs && node gen.mjs && node build.mjs
 *
 * Writes to files, not to stdout.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const head = `<!--
  MUAY THAI BANGKOK TONIGHT  (page address: /muay-thai-bangkok-tonight)
  Paste this whole thing into one HTML block (Tilda T123) on the page.

  Meta title, meta description, Open Graph and canonical are NOT in here.
  Tilda owns those; the text is in TILDA-PAGE-SETTINGS.txt.

  Every visible word is read from brief.txt (Part B) by extract-copy.mjs and
  gen.mjs. Do not edit this file by hand: change brief.txt and rebuild.

  The booking widget mounts into the element marked data-mtx-slot, at the foot
  of the page. It needs the MuayTix header block already pasted into Tilda Site
  Settings, More, HTML code for the HEAD.
-->
<div class="mtx-tn-page" id="mtx-tn">
<style>
`;

const schema = readFileSync('schema.json', 'utf8').trim();
const data = readFileSync('tonight-data.json', 'utf8').trim();
const parts = [head, readFileSync('style.css', 'utf8'), '</style>\n\n', readFileSync('body.html', 'utf8'), readFileSync('tail.html', 'utf8')];
const source = parts.join('').replace('@@SCHEMA@@', () => schema).replace('@@DATA@@', () => data);
if (/@@[A-Z_0-9]+@@/.test(source)) { console.error('A build token was left unfilled'); process.exit(1); }
writeFileSync('muay-thai-bangkok-tonight-source.html', source);

const live = source
  .replace(/<style>([\s\S]*?)<\/style>/g, (_, css) =>
    '<style>' + css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\n{3,}/g, '\n\n').trim() + '</style>')
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace(/\n{3,}/g, '\n\n')
  .trim() + '\n';

writeFileSync('muay-thai-bangkok-tonight-PASTE-INTO-TILDA.html', live);
console.log('source', (source.length / 1024).toFixed(1) + ' KB');
console.log('live  ', (live.length / 1024).toFixed(1) + ' KB  (muay-thai-bangkok-tonight-PASTE-INTO-TILDA.html)');
